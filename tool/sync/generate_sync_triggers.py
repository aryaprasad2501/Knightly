"""Writes lib/core/database/sync_tracking.drift: the sync bookkeeping tables and
the SQLite triggers that fill them. Re-run after adding a synced table, then
`dart run build_runner build` and a schema step (see docs/CLOUD_SYNC_PLAN.md).

Every insert/update of a synced row records (table, row key) in sync_outbox;
every delete records the cloud document id in sync_tombstones. Nothing is
recorded while sync itself is applying pulled data (sync_meta 'applying').
"""

from pathlib import Path

# (sql table, key expression on NEW/OLD for the outbox, doc id expression on OLD for tombstones)
UUID_TABLES = [
    'projects', 'tasks', 'task_checks', 'habits', 'events', 'routines', 'routine_steps',
    'routine_runs', 'water_logs', 'sleep_logs', 'workouts', 'workout_sets', 'workout_templates',
    'foods', 'meal_entries', 'care_jobs', 'care_logs',
]

# Settings that describe this phone, never synced (keep in step with
# `isDeviceOnlySetting` in lib/core/sync/sync_tables.dart).
DEVICE_ONLY = "{k} NOT LIKE 'backup.%' AND {k} NOT LIKE 'places.%' AND {k} NOT LIKE 'sync.%' AND {k} NOT IN ('home.fab_position', 'appearance.dock_launches', 'homecare.arrival', 'onboarding.welcome_seen')"

NOT_APPLYING = "NOT EXISTS (SELECT 1 FROM sync_meta WHERE \"key\" = 'applying')"


def outbox(table, key):
    # An upsert, not INSERT OR REPLACE: SQLite overrides a trigger's OR REPLACE
    # with the outer statement's policy (e.g. a foreign-key cascade).
    return (f"INSERT INTO sync_outbox (entity, row_key, changed_at) "
            f"VALUES ('{table}', {key}, strftime('%Y-%m-%dT%H:%M:%fZ', 'now')) "
            f"ON CONFLICT (entity, row_key) DO UPDATE SET changed_at = excluded.changed_at;")


def tomb(table, doc):
    return (f"INSERT INTO sync_tombstones (entity, doc_id, deleted_at) "
            f"VALUES ('{table}', {doc}, strftime('%Y-%m-%dT%H:%M:%fZ', 'now')) "
            f"ON CONFLICT (entity, doc_id) DO UPDATE SET deleted_at = excluded.deleted_at;")


def triggers(table, new_key, old_key, old_doc, extra_new='', extra_old=''):
    name = table
    out = []
    for when, row, key in [('INSERT', 'NEW', new_key), ('UPDATE', 'NEW', new_key)]:
        cond = NOT_APPLYING + (f' AND {extra_new}' if extra_new else '')
        out.append(
            f"CREATE TRIGGER sync_{name}_{when.lower()} AFTER {when} ON {table}\n"
            f"WHEN {cond}\nBEGIN\n  {outbox(table, key)}\nEND;\n"
        )
    cond = NOT_APPLYING + f' AND {old_doc} IS NOT NULL' + (f' AND {extra_old}' if extra_old else '')
    out.append(
        f"CREATE TRIGGER sync_{name}_delete AFTER DELETE ON {table}\n"
        f"WHEN {cond}\nBEGIN\n  {outbox_delete(table, old_key)}\n  {tomb(table, old_doc)}\nEND;\n"
    )
    return out


def outbox_delete(table, key):
    # A row deleted before it was pushed needs no upload any more.
    return f"DELETE FROM sync_outbox WHERE entity = '{table}' AND row_key = {key};"


parts = ['''-- Generated by tool/sync/generate_sync_triggers.py. Do not edit by hand.
-- Sync bookkeeping (schema v15): what changed locally since the last push,
-- what was deleted, and sync's own state. Never synced or backed up.

import 'app_database.dart';
import '../../features/tasks/data/tasks_tables.dart';
import '../../features/habits/data/habits_tables.dart';
import '../../features/calendar/data/calendar_tables.dart';
import '../../features/routines/data/routines_tables.dart';
import '../../features/water/data/water_tables.dart';
import '../../features/sleep/data/sleep_tables.dart';
import '../../features/workouts/data/workouts_tables.dart';
import '../../features/nutrition/data/nutrition_tables.dart';
import '../../features/home_care/data/home_care_tables.dart';

CREATE TABLE sync_outbox (
  entity TEXT NOT NULL,
  row_key TEXT NOT NULL,
  changed_at TEXT NOT NULL,
  PRIMARY KEY (entity, row_key)
) AS SyncOutboxRow;

CREATE TABLE sync_tombstones (
  entity TEXT NOT NULL,
  doc_id TEXT NOT NULL,
  deleted_at TEXT NOT NULL,
  PRIMARY KEY (entity, doc_id)
) AS SyncTombstoneRow;

CREATE TABLE sync_meta (
  "key" TEXT NOT NULL PRIMARY KEY,
  value TEXT NOT NULL
) AS SyncMetaRow;
''']

for t in UUID_TABLES:
    parts += triggers(t, 'NEW.uuid', 'OLD.uuid', 'OLD.uuid')

parts += triggers(
    'habit_check_ins',
    "NEW.habit_id || '|' || NEW.date",
    "OLD.habit_id || '|' || OLD.date",
    "(SELECT uuid FROM habits WHERE id = OLD.habit_id) || '_' || OLD.date",
)
parts += triggers(
    'event_exceptions',
    "NEW.event_id || '|' || NEW.date",
    "OLD.event_id || '|' || OLD.date",
    "(SELECT uuid FROM events WHERE id = OLD.event_id) || '_' || OLD.date",
)
parts += triggers(
    'app_settings',
    'NEW."key"',
    'OLD."key"',
    'OLD."key"',
    extra_new=DEVICE_ONLY.format(k='NEW."key"'),
    extra_old=DEVICE_ONLY.format(k='OLD."key"'),
)

out = Path(__file__).resolve().parents[2] / 'lib' / 'core' / 'database' / 'sync_tracking.drift'
out.write_text('\n'.join(parts), encoding='utf-8', newline='\n')
print(f'wrote {out} ({sum(p.startswith("CREATE TRIGGER") for p in parts)} triggers)')
