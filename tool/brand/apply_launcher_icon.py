"""Builds the Android launcher icon from the user-approved Dark Knight app icon
(KNIGHTLY_THEME_PACK/user_supplied/logos/DK-APP-ICON-APPROVED.png).

    python tool/brand/apply_launcher_icon.py [source.png] [--tile 0.07]

With no source, the approved Dark Knight icon is used. --tile is how far (as a
fraction of the width) the icon's rounded tile sits inside the image, for art
that has a margin around its tile (default 0: the tile fills the image).

Writes
  android/app/src/main/res/mipmap-*/ic_launcher.png             legacy icon (rounded tile)
  android/app/src/main/res/mipmap-*/ic_launcher_foreground.png  adaptive foreground (API 26+)
  android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml    adaptive icon definition
  branding/knightly_icon_512.png                                store listing

Supersedes the launcher part of tool/brand/generate_brand_assets_test.dart.
"""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'KNIGHTLY_THEME_PACK' / 'user_supplied' / 'logos' / 'DK-APP-ICON-APPROVED.png'
RES = ROOT / 'android' / 'app' / 'src' / 'main' / 'res'
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}


def rounded(im: Image.Image, radius: float) -> Image.Image:
    big = im.resize((im.width * 4, im.height * 4), Image.LANCZOS)
    mask = Image.new('L', big.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, big.width - 1, big.height - 1), radius=radius * 4, fill=255)
    big.putalpha(mask)
    return big.resize(im.size, Image.LANCZOS)


def main():
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument('source', nargs='?', default=str(SRC))
    parser.add_argument('--tile', type=float, default=0.0)
    args = parser.parse_args()
    icon = Image.open(args.source).convert('RGB')
    if args.tile > 0:
        edge = round(icon.width * args.tile)
        icon = icon.crop((edge, edge, icon.width - edge, icon.height - edge))
    for name, scale in DENSITIES.items():
        folder = RES / f'mipmap-{name}'
        folder.mkdir(exist_ok=True)
        px = round(48 * scale)
        tile = icon.resize((px, px), Image.LANCZOS)
        rounded(tile, px * 0.22).save(folder / 'ic_launcher.png')
        # Adaptive layer: 108 dp canvas; the launcher shows about the middle
        # 72 dp, so the artwork (minus its own glowing frame) fills ~80 %.
        canvas = round(108 * scale)
        inner = icon.crop((int(icon.width * 0.07),) * 2 + (int(icon.width * 0.93),) * 2)
        art = round(canvas * 0.8)
        layer = Image.new('RGBA', (canvas, canvas), (0, 0, 0, 0))
        layer.paste(inner.resize((art, art), Image.LANCZOS), ((canvas - art) // 2,) * 2)
        layer.save(folder / 'ic_launcher_foreground.png')
        # Monochrome layer (themed icons, Android 13+): the art's light areas
        # as a white shape. Without it, newer launchers shrink the icon onto
        # a tinted plate.
        grey = inner.convert('L').resize((art, art), Image.LANCZOS)
        alpha = grey.point(lambda v: max(0, min(255, (v - 45) * 2)))
        mono = Image.new('RGBA', (canvas, canvas), (0, 0, 0, 0))
        mono.paste(Image.new('RGBA', (art, art), (255, 255, 255, 255)), ((canvas - art) // 2,) * 2, alpha)
        mono.save(folder / 'ic_launcher_monochrome.png')
    (RES / 'mipmap-anydpi-v26' / 'ic_launcher.xml').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/brand/apply_launcher_icon.py from the user-approved app icon. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
        '</adaptive-icon>\n',
        encoding='utf-8',
    )
    rounded(icon.resize((512, 512), Image.LANCZOS), 512 * 0.22).save(ROOT / 'branding' / 'knightly_icon_512.png')
    print('launcher icon written')


if __name__ == '__main__':
    main()
