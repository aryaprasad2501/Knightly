// Generates Knightly's Android brand assets from the crest geometry used by
// `KCrestPainter`, so the launcher icon, splash and in-app mark never drift.
//
// Run from the project root (not part of the normal test suite):
//   flutter test tool/brand/generate_brand_assets_test.dart
//
// Writes:
//   android/app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml
//   android/app/src/main/res/mipmap-*/ic_launcher.png  (legacy, API < 26)
//   branding/knightly_icon_512.png                      (store listing)
import 'dart:io';
import 'dart:math' as math;
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:knightly/core/design/components/k_brand_mark.dart';
import 'package:knightly/core/design/theme/knightly_themes.dart';

const _res = 'android/app/src/main/res';

// The launcher always uses the default (Obsidian) identity.
final _palette = KnightlyThemeId.darkKnight.palette;

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('generate adaptive icon vectors', () {
    // Adaptive icons: 108 dp canvas, 66 dp safe circle. The crest box of 58
    // keeps every stroke inside the safe zone.
    const viewport = 108.0;
    const crest = 58.0;
    const origin = (viewport - crest) / 2;

    File('$_res/drawable/ic_launcher_background.xml').writeAsStringSync(_backgroundXml());
    File(
      '$_res/drawable/ic_launcher_foreground.xml',
    ).writeAsStringSync(_crestXml(origin: origin, size: crest, monochrome: false));
    File(
      '$_res/drawable/ic_launcher_monochrome.xml',
    ).writeAsStringSync(_crestXml(origin: origin, size: crest, monochrome: true));
  });

  test('generate legacy launcher PNGs and store icon', () async {
    const densities = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192};
    for (final MapEntry(key: density, value: px) in densities.entries) {
      await _writePng('$_res/mipmap-$density/ic_launcher.png', px, rounded: true);
    }
    Directory('branding').createSync();
    await _writePng('branding/knightly_icon_512.png', 512, rounded: false);
  });
}

String _hex(Color c) => '#${c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase()}';

String _n(double v) => v.toStringAsFixed(2);

/// Shield outline in viewport units — mirrors `KCrestPainter`.
String _shieldPath(double o, double s) {
  double x(double f) => o + s * f;
  return 'M${_n(x(0.5))},${_n(x(0.04))} '
      'L${_n(x(0.9))},${_n(x(0.18))} '
      'L${_n(x(0.9))},${_n(x(0.48))} '
      'C${_n(x(0.9))},${_n(x(0.74))} ${_n(x(0.7))},${_n(x(0.88))} ${_n(x(0.5))},${_n(x(0.97))} '
      'C${_n(x(0.3))},${_n(x(0.88))} ${_n(x(0.1))},${_n(x(0.74))} ${_n(x(0.1))},${_n(x(0.48))} '
      'L${_n(x(0.1))},${_n(x(0.18))} Z';
}

/// Crescent = circle 1 minus circle 2, expressed as two arcs between the
/// circles' intersection points.
String _crescentPath(double o, double s) {
  final c1 = Offset(o + s * 0.5, o + s * 0.48);
  final r1 = s * 0.22;
  final c2 = c1.translate(r1 * 0.55, -r1 * 0.2);
  final r2 = r1 * 0.9;

  final delta = c2 - c1;
  final d = delta.distance;
  final a = (r1 * r1 - r2 * r2 + d * d) / (2 * d);
  final h = math.sqrt(r1 * r1 - a * a);
  final u = delta / d;
  final normal = Offset(-u.dy, u.dx);
  final mid = c1 + u * a;
  final bottom = mid + normal * h;
  final top = mid - normal * h;

  return 'M${_n(top.dx)},${_n(top.dy)} '
      'A${_n(r1)},${_n(r1)} 0 1,0 ${_n(bottom.dx)},${_n(bottom.dy)} '
      'A${_n(r2)},${_n(r2)} 0 0,1 ${_n(top.dx)},${_n(top.dy)} Z';
}

String _crestXml({required double origin, required double size, required bool monochrome}) {
  final shield = _shieldPath(origin, size);
  final stroke = _n(size * 0.065);
  // Monochrome (themed) icons are tinted by the launcher: draw shapes only.
  final ink = monochrome ? '#FFFFFFFF' : _hex(_palette.accent);
  final moon = monochrome ? '#FFFFFFFF' : _hex(_palette.signal);
  final field = monochrome
      ? ''
      : '''
    <path
        android:fillColor="${_hex(_palette.surfaceRaised)}"
        android:pathData="$shield" />''';

  return '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_brand_assets_test.dart. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">$field
    <path
        android:fillColor="#00000000"
        android:strokeColor="$ink"
        android:strokeWidth="$stroke"
        android:strokeLineJoin="round"
        android:pathData="$shield" />
    <path
        android:fillColor="$moon"
        android:pathData="${_crescentPath(origin, size)}" />
</vector>
''';
}

String _backgroundXml() {
  final glow = _palette.ambient;
  final glowStart = _hex(glow.withValues(alpha: 0.42));
  final glowEnd = _hex(glow.withValues(alpha: 0));
  return '''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand/generate_brand_assets_test.dart. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="${_hex(_palette.canvas)}"
        android:pathData="M0,0h108v108h-108z" />
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="40"
                android:centerY="30"
                android:gradientRadius="72"
                android:startColor="$glowStart"
                android:endColor="$glowEnd" />
        </aapt:attr>
    </path>
</vector>
''';
}

Future<void> _writePng(String path, int px, {required bool rounded}) async {
  final size = px.toDouble();
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  final rect = Offset.zero & Size.square(size);

  final shape = rounded
      ? (Path()..addRRect(RRect.fromRectAndRadius(rect, Radius.circular(size * 0.22))))
      : (Path()..addRect(rect));
  canvas.clipPath(shape);
  canvas.drawRect(rect, Paint()..color = _palette.canvas);
  canvas.drawRect(
    rect,
    Paint()
      ..shader = RadialGradient(
        center: const Alignment(-0.26, -0.44),
        radius: 0.95,
        colors: [_palette.ambient.withValues(alpha: 0.42), _palette.ambient.withValues(alpha: 0)],
      ).createShader(rect),
  );

  final crest = size * 0.62;
  canvas.save();
  canvas.translate((size - crest) / 2, (size - crest) / 2);
  KCrestPainter(
    shield: _palette.accent,
    moon: _palette.signal,
    field: _palette.surfaceRaised,
  ).paint(canvas, Size.square(crest));
  canvas.restore();

  final image = await recorder.endRecording().toImage(px, px);
  final bytes = await image.toByteData(format: ui.ImageByteFormat.png);
  File(path).writeAsBytesSync(bytes!.buffer.asUint8List());
}
